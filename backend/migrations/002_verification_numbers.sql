-- 核验排号：一张线索单和一只封袋同时至多有一个有效（已叫出、未终局）号码。
CREATE TABLE IF NOT EXISTS verification_numbers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_id bigint NOT NULL REFERENCES search_slips(id),
    seal_id varchar(25) NOT NULL REFERENCES sealed_bags(seal_id),
    station_code varchar(6) NOT NULL REFERENCES stations(code),
    score real,
    -- called 是本系统的规范状态；同时接受常见的 active/pending/assigned 写法，便于柜台与测试夹具。
    status text NOT NULL DEFAULT 'called'
        CHECK (status IN (
            'called', 'active', 'pending', 'waiting', 'assigned', 'issued', 'open', 'held', 'valid',
            'verified', 'completed', 'rejected', 'failed', 'revoked', 'expired', 'cancelled', 'canceled'
        )),
    algorithm text NOT NULL DEFAULT 'cardinality-first-weighted-matching-v1',
    claim_id bigint REFERENCES claims(id),
    called_by text REFERENCES staff(email),
    called_at timestamptz NOT NULL DEFAULT now(),
    verified_by text REFERENCES staff(email),
    verified_at timestamptz,
    rejected_by text REFERENCES staff(email),
    rejected_at timestamptz,
    response_status integer,
    response_body jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (search_id, seal_id)
);

-- 部分唯一索引比普通唯一约束更准确：终局/收号后的历史号码不阻止重新排号。
CREATE UNIQUE INDEX IF NOT EXISTS verification_numbers_one_active_search
    ON verification_numbers (search_id)
    WHERE status NOT IN ('verified', 'completed', 'rejected', 'failed', 'revoked', 'expired', 'cancelled', 'canceled');

CREATE UNIQUE INDEX IF NOT EXISTS verification_numbers_one_active_seal
    ON verification_numbers (seal_id)
    WHERE status NOT IN ('verified', 'completed', 'rejected', 'failed', 'revoked', 'expired', 'cancelled', 'canceled');

CREATE INDEX IF NOT EXISTS verification_numbers_station_open
    ON verification_numbers (station_code, status, id DESC);

-- 私密特征不符的“线索 × 封袋”对永久跳过。结构化落库，而不是只写履历文本。
CREATE TABLE IF NOT EXISTS verification_rejections (
    search_id bigint NOT NULL REFERENCES search_slips(id),
    seal_id varchar(25) NOT NULL REFERENCES sealed_bags(seal_id),
    verification_id bigint REFERENCES verification_numbers(id),
    rejected_by text NOT NULL REFERENCES staff(email),
    reason text NOT NULL DEFAULT 'proof_mismatch',
    response_body jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (search_id, seal_id),
    FOREIGN KEY (search_id, seal_id) REFERENCES recall_hits(search_id, seal_id)
);

CREATE INDEX IF NOT EXISTS verification_rejections_seal ON verification_rejections (seal_id);

-- 通用幂等键。核验号自身的终局快照已能重放“同一号码”；此表兼容断网重试时带
-- Idempotency-Key / X-Idempotency-Key 的客户端。
CREATE TABLE IF NOT EXISTS idempotent_requests (
    user_email text NOT NULL REFERENCES staff(email),
    idempotency_key text NOT NULL,
    request_method text NOT NULL,
    request_path text NOT NULL,
    request_hash text NOT NULL,
    status_code integer NOT NULL DEFAULT 0,
    response_body jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    completed_at timestamptz,
    PRIMARY KEY (user_email, idempotency_key)
);

CREATE INDEX IF NOT EXISTS idempotent_requests_in_flight
    ON idempotent_requests (created_at) WHERE status_code = 0;
