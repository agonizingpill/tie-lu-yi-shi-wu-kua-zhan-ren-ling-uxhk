CREATE TABLE IF NOT EXISTS stations (
    code varchar(6) PRIMARY KEY,
    display_name text NOT NULL,
    corridor_position integer NOT NULL UNIQUE CHECK (corridor_position > 0)
);

CREATE TABLE IF NOT EXISTS staff (
    email text PRIMARY KEY,
    display_name text NOT NULL,
    role text NOT NULL CHECK (role IN ('clerk', 'dispatcher', 'observer')),
    station_code varchar(6) REFERENCES stations(code),
    salt text NOT NULL,
    password_hash text NOT NULL,
    CHECK ((role = 'clerk') = (station_code IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS sealed_bags (
    seal_id varchar(25) PRIMARY KEY,
    origin_station varchar(6) NOT NULL REFERENCES stations(code),
    current_station varchar(6) NOT NULL REFERENCES stations(code),
    train_no varchar(12) NOT NULL,
    found_on date NOT NULL,
    category text NOT NULL CHECK (category IN ('包袋', '衣物', '数码', '票证', '配件')),
    color varchar(32) NOT NULL,
    description varchar(160) NOT NULL,
    proof_digest varchar(64) NOT NULL,
    state text NOT NULL DEFAULT 'sealed' CHECK (state IN ('sealed', 'reserved', 'in_transit', 'released')),
    recorded_by text NOT NULL REFERENCES staff(email),
    recorded_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS search_slips (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category text NOT NULL CHECK (category IN ('包袋', '衣物', '数码', '票证', '配件')),
    color varchar(32) NOT NULL,
    description varchar(160) NOT NULL,
    travel_on date NOT NULL,
    train_no varchar(12),
    entered_at varchar(6) NOT NULL REFERENCES stations(code),
    entered_by text NOT NULL REFERENCES staff(email),
    status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'ranked', 'failed')),
    model_summary jsonb,
    queued_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS recall_hits (
    search_id bigint NOT NULL REFERENCES search_slips(id),
    seal_id varchar(25) NOT NULL REFERENCES sealed_bags(seal_id),
    rank integer NOT NULL CHECK (rank > 0),
    score real NOT NULL CHECK (score BETWEEN 0 AND 1),
    exact_features integer NOT NULL CHECK (exact_features >= 0),
    collision_slots integer NOT NULL CHECK (collision_slots >= 0),
    auditable boolean NOT NULL,
    PRIMARY KEY (search_id, seal_id),
    UNIQUE (search_id, rank)
);

CREATE TABLE IF NOT EXISTS claims (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_id bigint NOT NULL,
    seal_id varchar(25) NOT NULL,
    pickup_station varchar(6) NOT NULL REFERENCES stations(code),
    status text NOT NULL CHECK (status IN ('verified', 'released')),
    verified_by text NOT NULL REFERENCES staff(email),
    released_by text REFERENCES staff(email),
    released_at timestamptz,
    FOREIGN KEY (search_id, seal_id) REFERENCES recall_hits(search_id, seal_id),
    UNIQUE (search_id),
    UNIQUE (seal_id)
);

CREATE TABLE IF NOT EXISTS transfers (
    code varchar(22) PRIMARY KEY,
    claim_id bigint NOT NULL UNIQUE REFERENCES claims(id),
    from_station varchar(6) NOT NULL REFERENCES stations(code),
    to_station varchar(6) NOT NULL REFERENCES stations(code),
    carrier_train varchar(12) NOT NULL,
    state text NOT NULL DEFAULT 'dispatched' CHECK (state IN ('dispatched', 'received')),
    dispatched_by text NOT NULL REFERENCES staff(email),
    dispatched_at timestamptz NOT NULL DEFAULT now(),
    received_by text REFERENCES staff(email),
    received_at timestamptz,
    CHECK (from_station <> to_station)
);

CREATE TABLE IF NOT EXISTS custody_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seal_id varchar(25) NOT NULL REFERENCES sealed_bags(seal_id),
    actor text NOT NULL REFERENCES staff(email),
    action text NOT NULL,
    detail text NOT NULL,
    at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS available_seal_lookup ON sealed_bags (state, found_on);
CREATE INDEX IF NOT EXISTS custody_ledger_lookup ON custody_events (seal_id, id DESC);
